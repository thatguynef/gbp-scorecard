#!/usr/bin/env python3
"""Render references/rubric.md from the canonical rubric.

Usage:
  python3 render_rubric.py
  python3 render_rubric.py --check
  python3 render_rubric.py --rubric path --out path
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_RUBRIC = HERE.parent / "references" / "rubric.json"
DEFAULT_OUT = HERE.parent / "references" / "rubric.md"
DOCS_OUT = HERE.parent.parent.parent.parent / "docs" / "rubric.md"


def render(rubric: dict) -> str:
    lines = [
        "# Google Business Profile Scorecard — Canonical Rubric",
        "",
        "> **Generated from `rubric.json`.** Do not edit this file by hand. Run `python3 render_rubric.py`.",
        "",
        f"**Version:** {rubric['version']} · **Framework:** `{rubric['framework']}` · **Updated:** {rubric['updated']} · **Total:** {rubric['total']}",
        "",
        rubric.get("subtitle", ""),
        "",
        "## The seven categories",
        "",
        "| Category | Weight | Question |",
        "|---|---:|---|",
    ]
    for cat in rubric["categories"]:
        lines.append(f"| {cat['id']}. {cat['name']} | {cat['max']} | {cat['question']} |")
    lines += [
        "| **Total** | **100** | |",
        "",
        "The score is not a completeness score. Conversion receives the highest weight because a profile that cannot produce a next step has failed its main job.",
        "",
        "## Bands",
        "",
        "| Score | Band | Label |",
        "|---:|---|---|",
    ]
    for band in sorted(rubric["bands"], key=lambda b: -b["min"]):
        lines.append(f"| {band['min']}–{min(100, band['min'] + 14) if band['min'] < 90 else 100} | {band['band']} | {band['label']} |")
    lines += [
        "",
        "## Scoring model",
        "",
        rubric["scoring"]["formula"],
        "",
        f"**Rounding.** {rubric['scoring']['rounding']}",
        "",
        f"**Owner data.** {rubric['scoring']['owner_data']}",
        "",
        f"**Evidence.** {rubric['scoring']['evidence']}",
        "",
        "## Check index",
        "",
        "| ID | Title | Cat | Max | Severity | Evaluation | Applicability |",
        "|---|---|---|---:|---|---|---|",
    ]
    for item in rubric["items"]:
        applicability = item["applicability"]
        if item.get("condition"):
            applicability += f" (`{item['condition']}`)"
        lines.append(
            f"| {item['id']} | {item['title']} | {item['cat']} | {item['max']} | "
            f"{item['severity']} | {item['evaluation']} | {applicability} |"
        )
    lines += ["", "## Checks by category", ""]
    for cat in rubric["categories"]:
        lines += [f"### {cat['id']}. {cat['name']} — {cat['max']} points", "", cat["question"], ""]
        for item in [i for i in rubric["items"] if i["cat"] == cat["id"]]:
            condition = ""
            if item.get("condition"):
                condition = f" · condition: `{item['condition']}`"
            if item.get("requires"):
                condition += f" · requires: `{item['requires']}`"
            rad = f" · RAD: `{item['radModule']}`" if item.get("radModule") else ""
            lines += [
                f"#### {item['id']} — {item['title']} ({item['max']} points)",
                "",
                f"**Stage:** {item['journeyStage']} · **Severity:** {item['severity']} · "
                f"**Evaluation:** {item['evaluation']} · **Applicability:** {item['applicability']}{condition}{rad}",
                "",
                f"**Principle:** {item['principle']}",
                "",
                "| Score | Anchor |",
                "|---:|---|",
            ]
            for value in item["allowed"]:
                lines.append(f"| {value} | {item['anchors'][str(value)]} |")
            lines += [
                "",
                f"**Evidence to capture:** {item['evidence']}",
                "",
                f"**Recommended intervention:** {item['recommendedIntervention']}",
                "",
            ]
    lines += [
        "## Hard caps",
        "",
        "A cap is exceptional. It exists only where an observable failure can invalidate the rest of the diagnosis.",
        "",
        "| Cap | Scope | Cap | Deterministic trigger | Rationale |",
        "|---|---|---:|---|---|",
    ]
    for cap in rubric["caps"]:
        scope = cap["scope"] if cap["scope"] == "overall" else f"category {cap['category']}"
        trigger = "; ".join(
            f"{c['fact']} " + (f"= {c['equals']}" if "equals" in c else f"in {c['in']}") for c in cap["trigger"]["all"]
        )
        lines.append(f"| {cap['label']} (`{cap['id']}`) | {scope} | {cap['max']} | {trigger} | {cap['rationale']} |")
    lines += [
        "",
        "Category caps apply to the normalized category points before the overall cap. A cap is applied once. The verifier recomputes every trigger from `facts`.",
        "",
        "## Journey stages",
        "",
        "| # | Stage | Coverage | Customer question | Checks | Owner data |",
        "|---:|---|---|---|---|---|",
    ]
    for stage in sorted(rubric["journey"], key=lambda s: s["order"]):
        lines.append(
            f"| {stage['order']} | {stage['label']} | {stage['coverageStatus']} | {stage['customerQuestion']} | "
            f"{', '.join(stage['checks']) or '—'} | {', '.join(stage['ownerData']) or '—'} |"
        )
    lines += [
        "",
        "## Owner-data questions (never scored)",
        "",
        "These questions require CRM, phone, booking, messaging, or financial data. They do not reduce the public score.",
        "",
        "| ID | Stage | Question | Why it matters |",
        "|---|---|---|---|",
    ]
    for entry in rubric["ownerData"]:
        lines.append(f"| {entry['id']} | {entry['journeyStage']} | {entry['title']} | {entry['whyItMatters']} |")
    lines += [
        "",
        "## Opportunity flags (never scored)",
        "",
        "An optional RAD service is never the reason a business loses points.",
        "",
        "| Flag | RAD module | Why it may matter |",
        "|---|---|---|",
    ]
    for opportunity in rubric["opportunities"]:
        lines.append(f"| {opportunity['label']} | `{opportunity['radModule']}` | {opportunity['why']} |")
    lines += [
        "",
        "## Cross-scorecard boundaries",
        "",
        "| Question | GBP Scorecard | Website Scorecard | Local Visibility |",
        "|---|---|---|---|",
    ]
    for row in rubric.get("crossScorecard", []):
        lines.append(f"| {row['question']} | {row['gbp']} | {row['website']} | {row['visibility']} |")
    lines += [
        "",
        "The same defect is not scored by two scorecards in one run. The only deliberate overlap is HTTPS at the handoff; GBP caps Handoff, while Website Scorecard judges the owned site.",
        "",
        "## Fix mapping",
        "",
        "Each check has a deterministic fix mapping in `rubric.json`. A mapping is metadata, not a sales recommendation.",
        "",
        "| Check | Priority | Fix | RAD modules |",
        "|---|---|---|---|",
    ]
    for fix in rubric["fixes"]:
        lines.append(
            f"| {fix['checkId']} | {fix['priority']} | {fix['fix']} | {', '.join(f'`{m}`' for m in fix['radModules']) or '—'} |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Render the GBP rubric as Markdown.")
    parser.add_argument("--rubric", default=str(DEFAULT_RUBRIC))
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    parser.add_argument("--docs-out", default=str(DOCS_OUT))
    parser.add_argument("--check", action="store_true", help="Fail if the output is stale.")
    args = parser.parse_args()
    try:
        rubric = json.loads(Path(args.rubric).read_text(encoding="utf-8"))
    except (FileNotFoundError, json.JSONDecodeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    rendered = render(rubric)
    docs_rendered = (
        '---\ndescription: "The canonical 49-check GBP rubric: seven weighted categories, exact score anchors, evidence rules, five hard caps, owner-data questions, and opportunity flags."\n---\n\n'
        + rendered
    )
    outputs = [(Path(args.out), rendered), (Path(args.docs_out), docs_rendered)]
    if args.check:
        for out, expected in outputs:
            current = out.read_text(encoding="utf-8") if out.exists() else ""
            if current != expected:
                print(f"error: {out} is stale. Run: python3 {Path(__file__).name}", file=sys.stderr)
                return 1
            print(f"ok: {out} is current")
        return 0
    for out, expected in outputs:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(expected, encoding="utf-8")
        print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
